function applyTestCatalogMetadata(tests: any[]) {
  tests.forEach((test) => {
    const metadata = testCatalogMetadata[test.id];
    if (metadata) {
      Object.assign(test, metadata);
      if (!("coverageNote" in metadata)) delete test.coverageNote;
    }
  });
  return tests;
}

function applyTwoLevelTestStructure(tests: any[]) {
  tests.forEach((test) => {
    const splitIndex = Math.ceil(test.questions.length / 2);
    test.questions.forEach((question: any, index: number) => {
      if (question.level !== "basic" && question.level !== "advanced") {
        question.level = index < splitIndex ? "basic" : "advanced";
      }
    });
  });
  return tests;
}

