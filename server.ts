function refreshDefaultTheoryArticles(targetSyllabus: any[], sourceSyllabus: typeof syllabusData, articleIds: string[]) {
  const sourceArticles = new Map<string, any>();
  for (const chapter of sourceSyllabus) {
    for (const section of chapter.sections || []) {
      for (const subsection of section.subsections || []) sourceArticles.set(subsection.id, subsection);
    }
  }

  for (const chapter of targetSyllabus) {
    for (const section of chapter.sections || []) {
      for (const subsection of section.subsections || []) {
        if (!articleIds.includes(subsection.id)) continue;
        const source = sourceArticles.get(subsection.id);
        if (!source) continue;
        for (const field of ["content", "tables", "list", "keyTerms", "formulas", "gostReference"]) {
          if (field in source) subsection[field] = JSON.parse(JSON.stringify(source[field]));
          else delete subsection[field];
        }
      }
    }
  }
}

function separateProjectGuidanceFromDrawing(targetSyllabus: any[], sourceSyllabus: typeof syllabusData) {
  const drawingChapter = targetSyllabus.find((chapter: any) => chapter.id === "7");
  const existingProjectChapter = targetSyllabus.find((chapter: any) => chapter.id === "project");
  const oldProjectSection = drawingChapter?.sections?.find((section: any) => section.id === "7.3");

  if (!existingProjectChapter) {
    if (oldProjectSection) {
      const movedSection = JSON.parse(JSON.stringify(oldProjectSection));
      movedSection.id = "project.1";
      movedSection.title = "Тема года, направления и требования";
      movedSection.subsections?.forEach((subsection: any) => {
        subsection.id = subsection.id.replace(/^7\.3\./, "project.1.");
      });
      targetSyllabus.push({
        id: "project",
        title: "Проектная подготовка 2026/2027",
        sections: [movedSection]
      });
    } else {
      mergeDefaultProjectGuidance(targetSyllabus, sourceSyllabus);
    }
  }

  if (drawingChapter) {
    if (targetSyllabus.some((chapter: any) => chapter.id === "project")) {
      drawingChapter.sections = drawingChapter.sections?.filter((section: any) => section.id !== "7.3") || [];
    }
    if (drawingChapter.title === "7. Творческий проект, чертежи и ГОСТы") {
      drawingChapter.title = "7. Черчение, ЕСКД и технологическая документация";
    }
  }
}

