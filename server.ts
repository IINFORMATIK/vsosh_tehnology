function mergeDefaultMaterialImages(targetSyllabus: any[], sourceSyllabus: typeof syllabusData) {
  const imagesBySubsection = new Map<string, any[]>();
  sourceSyllabus.forEach((chapter) => {
    chapter.sections?.forEach((section) => {
      section.subsections.forEach((subsection) => {
        if (subsection.images?.length) {
          imagesBySubsection.set(subsection.id, subsection.images);
        }
      });
    });
  });

  targetSyllabus.forEach((chapter) => {
    chapter.sections?.forEach((section: any) => {
      section.subsections?.forEach((subsection: any) => {
        const defaultImages = imagesBySubsection.get(subsection.id);
        if (defaultImages && !subsection.images?.length) {
          subsection.images = defaultImages;
        }
      });
    });
  });
}

